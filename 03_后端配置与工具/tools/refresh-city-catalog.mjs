// Refresh the checked-in mainland city catalogue from AMap. No Key is exported.
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, resolve } from 'node:path';
import { createRequire } from 'node:module';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const require = createRequire(resolve(root, 'api/package.json'));
const { parse } = require('dotenv');
const key = parse(readFileSync(resolve(root, 'api/.env'), 'utf8')).AMAP_KEY;
if (!key) throw new Error('请先配置 api/.env 中的 AMAP_KEY');
const url = new URL('https://restapi.amap.com/v3/config/district');
for (const [name, value] of Object.entries({ key, keywords: '中国', subdistrict: '3', extensions: 'base' })) {
  url.searchParams.set(name, value);
}
let payload;
try {
  const response = await fetch(url, { signal: AbortSignal.timeout(30000) });
  if (!response.ok) throw new Error();
  payload = await response.json();
} catch {
  throw new Error('行政区目录下载失败，请检查网络后重试（未输出密钥）');
}
if (payload.status !== '1') throw new Error(`高德行政区查询失败：${payload.info}`);
const country = payload.districts?.[0];
if (!country?.districts?.length) throw new Error('行政区响应缺少省份');
const municipalities = new Set(['110000', '120000', '310000', '500000']);
const excluded = new Set(['710000', '810000', '820000']);
const provinces = country.districts.filter(p => !excluded.has(p.adcode)).map(p => {
  const cities = [];
  const add = (node, field) => cities.push({ code: node.adcode, name: node.name, field });
  if (municipalities.has(p.adcode)) {
    add(p, 'city');
  } else {
    for (const node of p.districts || []) {
      if (/直辖县级行政|直辖行政单位/.test(node.name)) {
        for (const child of node.districts || []) add(child, 'district');
      } else if (node.level === 'district') {
        add(node, 'district');
      } else if (node.level === 'city') {
        // AMap sometimes labels province-administered counties as level=city.
        // Their six-digit codes do not end in 00; reverse geocoding uses district.
        add(node, node.adcode.endsWith('00') ? 'city' : 'district');
      }
    }
  }
  cities.sort((a, b) => a.code.localeCompare(b.code));
  return { code: p.adcode, name: p.name, cities };
}).sort((a, b) => a.code.localeCompare(b.code));
if (provinces.length !== 31 || provinces.some(p => !p.cities.length)) {
  throw new Error('大陆省级目录不完整，未更新文件');
}
const catalogue = {
  source: 'https://lbs.amap.com/api/webservice/guide/api/district',
  updatedAt: new Date().toISOString().slice(0, 10),
  scope: '中国大陆省市及省直辖县级行政区，不含普通区县',
  provinces
};
mkdirSync(resolve(root, 'miniprogram/data'), { recursive: true });
writeFileSync(resolve(root, 'miniprogram/data/cities.js'), '// Generated by tools/refresh-city-catalog.mjs; do not edit manually.\nmodule.exports = ' + JSON.stringify(catalogue, null, 2) + ';\n');
writeFileSync(resolve(root, 'api/src/spots/mainland-regions.json'), JSON.stringify(catalogue, null, 2) + '\n');
console.log(`目录已更新：${provinces.length} 个省级地区，${provinces.reduce((n, p) => n + p.cities.length, 0)} 个可选地区`);
for (const p of provinces) console.log(`${p.name}: ${p.cities.length} 项；省直辖：${p.cities.filter(c => c.field === 'district').map(c => c.name).join('、') || '无'}`);
